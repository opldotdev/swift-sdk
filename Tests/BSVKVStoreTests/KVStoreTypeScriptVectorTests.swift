/// A LocalKVStore token produced by `@bsv/sdk` 4.1.1 itself (ts-stack
/// `3b1abc569`) under bun, the way `LocalKVStore.set` writes an unencrypted
/// value (`kvstore/LocalKVStore.ts:171-173, 492-497`), and checked the way
/// `LocalKVStore` reads it (lines 283-302):
///
/// ```ts
/// const { PrivateKey, ProtoWallet, PushDrop, Utils } = await import(`${process.env.TS_SDK}/mod.ts`)
/// const wallet = new ProtoWallet(new PrivateKey(42))
/// const value = Utils.toArray('hello kv', 'utf8')
/// const script = await new PushDrop(wallet).lock([value], [2, 'kvstore default'], 'greeting', 'self')
/// const decoded = PushDrop.decode(script)
/// await wallet.verifySignature({ data: decoded.fields[0], signature: decoded.fields[1],
///   protocolID: [2, 'kvstore default'], keyID: 'greeting', counterparty: 'self' }) // valid
/// console.log(script.toHex())
/// ```
@Suite("LocalKVStore token generated by TypeScript")
struct KVStoreTypeScriptVectorTests {
    private static let scriptHex =
        "210368b159848545d295de98caec206c3d6d50a8614b4f348b2c25cdc43db3e8ea98ac0868656c6c6f206b76473045022100f5993b196842d2974321bcea41f7c9999d82cb3c2bfa67f05c57fdc487d8c48002202b2bdff403c31de8fbe952fd4aef058646da719bcc488c344a7a5f1c0bb07a456d"

    @Test("Swift decodes the TypeScript token and its wallet writes the same bytes")
    func typeScriptToken() async throws {
        let script = try Script(
            bytes: Hex.decode(Self.scriptHex, maximumDecodedByteCount: 1_000),
            maximumByteCount: 1_000
        )
        let wallet = ProtoWallet(
            rootKey: try PrivateKey([UInt8](repeating: 0, count: 31) + [42])
        )
        let locator = try KVStoreLocator(context: "kvstore default", key: "greeting")
        let token = try await KVStoreTokenCodec.decode(script, locator: locator, using: wallet)
        #expect(token.value == Array("hello kv".utf8))

        let swiftScript = try await KVStoreTokenCodec.lockingScript(
            value: Array("hello kv".utf8),
            locator: locator,
            using: wallet
        )
        // Same key derivation and deterministic low-S signature: byte for byte.
        #expect(Hex.encode(swiftScript.bytes) == Self.scriptHex)
    }
}
